def generate_schedules(name, config, log):
    """Run SparseAuto's enumeration + depth + z3 pruning; return its baskets."""
    stem = f"finchbench_{name}"
    full = {
        **config,
        "output_tensor": "A",
        "test_name": stem,
        "test_json_file": f"{stem}_without_z3_pruning.json",
        "test_json_file_without_depth": f"{stem}_without_depth_pruning.json",
        "test_json_file_after_z3": f"{stem}_with_z3_pruning.json",
    }
    (SCHEDULER / f"test_configs/{stem}_config.json").write_text(json.dumps(full, indent=2))
    # Fresh process per benchmark: the scheduler leaks state between in-process
    # calls. Its worker processes rely on fork (Linux default) to inherit globals
    # set in main(); under macOS's spawn they crash and silently drop schedules.
    script = ("import multiprocessing, sys; multiprocessing.set_start_method('fork'); "
              "from src import main_store_json, main_store_json_z3; "
              "main_store_json.main(['-f', sys.argv[1]]); main_store_json_z3.main(['-f', sys.argv[1]])")
    log.flush()
    subprocess.run([sys.executable, "-c", script, f"{stem}_config.json"],
                   cwd=SCHEDULER, stdout=log, stderr=subprocess.STDOUT, check=True)
    baskets, accesses = read_baskets_from_json(str(SCHEDULER / f"test_schedules/{full['test_json_file_after_z3']}"))
    return baskets, accesses


def schedule_code(name, accesses, config):
    visitor = UnfusedConfigToTacoVisitor(f"finchbench_{name}", accesses, config.original_idx_perm,
                                         str(TEST_FILE), THREADS)
    visitor.visit(deepcopy(config))
    return visitor


def build_taco_test():
    result = subprocess.run(["cmake", "--build", str(BUILD), "--target", "taco-test", "-j8"],
                            capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(f"taco-test build failed:\n{result.stdout[-3000:]}\n{result.stderr[-3000:]}")


def run_case(name, case):
    env = {**os.environ, **case["env"], "OMP_NUM_THREADS": str(THREADS), "ITERATIONS": str(TRIALS + 1)}
    result = subprocess.run([str(BUILD / "bin/taco-test"), f"--gtest_filter=finchbench.{name}"],
                            env=env, capture_output=True, text=True, timeout=3000)
    lines = result.stdout.splitlines()
    times = [float(line.split()[1]) / 1000 for line in lines if line.startswith("FINCHBENCH_MS")]
    checksum = [float(line.split()[1]) for line in lines if line.startswith("FINCHBENCH_SUM")]
    if result.returncode or len(times) != TRIALS + 1 or not checksum:
        raise RuntimeError(f"taco-test {name} failed:\n{result.stdout[-3000:]}\n{result.stderr[-3000:]}")
    if not np.isclose(checksum[0], case["expected"], rtol=1e-7, atol=1e-9):
        raise RuntimeError(f"{name}: wrong result (sum {checksum[0]} != {case['expected']})")
    return times[1:]  # drop warmup


def benchmark(name, test, make_benchmark, directory, log):
    config, cases = make_benchmark(directory)
    print(f"Scheduling {name} with SparseAuto", flush=True)
    baskets, accesses = generate_schedules(name, config, log)

    # Candidates per case: the basket SparseAuto's cost model picks for its sizes.
    schedules = {}  # schedule text -> (visitor, [case indices])
    for index, case in enumerate(cases):
        with contextlib.redirect_stdout(log):
            _, _, best = baskets.filter_with_final_constraints(case["actual"], ALLOWED_ELEMENT_SIZE)
        for candidate in best[2]:
            visitor = schedule_code(name, accesses, candidate)
            text = visitor.wrap_in_block(visitor.get_combined_schedule())
            schedules.setdefault(text, (visitor, []))[1].append(index)

    # Only this benchmark's test goes in the file: an empty BEGIN/END block
    # leaves `stmt` undeclared and would break the build.
    TEST_FILE.write_text(HEADER + test)
    subprocess.run(["cmake", "-S", str(TACO), "-B", str(BUILD)], check=True, capture_output=True)
    timings = {index: [] for index in range(len(cases))}
    for number, (visitor, indices) in enumerate(schedules.values(), start=1):
        print(f"  compiling schedule {number}/{len(schedules)}", flush=True)
        with contextlib.redirect_stdout(log):
            visitor.write_to_file()
        build_taco_test()
        for index in indices:
            timings[index].append(run_case(name, cases[index]))
    return [(cases[index]["density"], min(samples, key=statistics.median))
            for index, samples in timings.items()]


def fixed_benchmarks(directory):
    """Build the hand-scheduled kernels once and time every case."""
    cases = spgemm_benchmark(directory) + matrix_feature_benchmark(directory)
    TEST_FILE.write_text(HEADER + SPGEMM_TEST + FEATURES_TEST)
    subprocess.run(["cmake", "-S", str(TACO), "-B", str(BUILD)], check=True, capture_output=True)
    print("Compiling SpGEMM / matrix feature kernels", flush=True)
    build_taco_test()
    return [(test, parameter, run_case(test, case)) for test, parameter, case in cases]


def run(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("graph/scripts/sparseauto_result.csv"))
    args = parser.parse_args(argv)
    output_path = args.output.resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    os.chdir(SCHEDULER)  # the scheduler uses paths relative to its own directory
    try:
        with tempfile.TemporaryDirectory() as directory, \
                (SCHEDULER / "temp/finchbench.log").open("w") as log, \
                output_path.open("w", newline="") as output:
            writer = csv.writer(output)
            writer.writerow(("benchmark", "density", "active_k", "repeat", "seconds"))
            for name, test, make_benchmark in (("sddmm", SDDMM_TEST, sddmm_benchmark),
                                               ("chain", CHAIN_TEST, chain_benchmark)):
                for density, samples in benchmark(name, test, make_benchmark, directory, log):
                    for trial, seconds in enumerate(samples):
                        writer.writerow((name, density, "", trial, seconds))
                    output.flush()
                    print(f"{name}: density={density:.6g}, median={statistics.median(samples):.6g}s",
                          flush=True)
            for test, parameter, samples in fixed_benchmarks(directory):
                if test == "features":
                    name, row = f"features_{parameter}", (feature_matrix.DENSITY, "")
                    label = f"density={feature_matrix.DENSITY:g}"
                else:
                    name, row, label = test, ("", parameter), f"active_k={parameter}"
                for trial, seconds in enumerate(samples):
                    writer.writerow((name, *row, trial, seconds))
                output.flush()
                print(f"{name}: {label}, median={statistics.median(samples):.6g}s", flush=True)
    finally:
        TEST_FILE.unlink(missing_ok=True)
    print(f"Saved {output_path}")


if __name__ == "__main__":
    run()
