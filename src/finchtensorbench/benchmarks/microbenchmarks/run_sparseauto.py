def random_csr(shape, density, seed):
    return sps.csr_array(sps.random(
        *shape, density=density, format="csr",
        random_state=np.random.default_rng(seed), data_rvs=np.ones,
    ))


def write_mtx(directory, name, matrix):
    path = Path(directory) / f"{name}.mtx"
    scipy.io.mmwrite(path, sps.coo_matrix(matrix, dtype=np.float64))
    return str(path)


def dense_fill(rows, cols):
    r, c = np.indices((rows, cols))
    return ((r * 31 + c * 17) % 13) / 13.0


def exact(sizes):
    return [f"{index} {op} {size}" for index, size in sizes.items() for op in (">=", "<=")]


def pos(matrix):
    return max(1, round(matrix.nnz / matrix.shape[0]))


